import * as XLSX from 'xlsx'
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import { createClient } from '@sanity/client'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)

const DEFAULT_SHEET_URL = 'https://docs.google.com/spreadsheets/d/e/2PACX-1vQlNHAbUt7ldY7my-EXF1VZq4s2eQ7y3YzZm8z6vFLfUH4KYKHw3G03FK60DlgQ_fGUN1Hz1qIBFqUT/pub?output=xlsx'

async function getSheetUrl() {
  try {
    const sanityClient = createClient({
      projectId: process.env.NEXT_PUBLIC_SANITY_PROJECT_ID || '8xtd7yiv',
      dataset: process.env.NEXT_PUBLIC_SANITY_DATASET || 'production',
      apiVersion: '2024-07-09',
      useCdn: false,
      token: process.env.SANITY_WRITE_TOKEN || process.env.SANITY_API_TOKEN
    })
    const siteSettings = await sanityClient.fetch(`*[_type == "siteSettings"][0]{ attractionsSheetUrl }`)
    if (siteSettings?.attractionsSheetUrl) {
      let url = siteSettings.attractionsSheetUrl
        .replace(/\/pubhtml.*/gi, '/pub?output=xlsx')
        .replace(/output=csv/gi, 'output=xlsx')
        .replace(/output=html/gi, 'output=xlsx')
      if (!url.includes('output=xlsx')) {
        url += (url.includes('?') ? '&' : '?') + 'output=xlsx'
      }
      return url
    }
  } catch (err) {
    console.log('Using default Google Sheet URL (siteSettings fetch skipped or failed)')
  }
  return DEFAULT_SHEET_URL
}

async function syncAttractions() {
  console.log('🔄 Starting Attraction Names Sync from Google Sheets...')
  const sheetUrl = await getSheetUrl()
  console.log(`📡 Fetching Google Sheet from: ${sheetUrl}`)

  const res = await fetch(sheetUrl)
  if (!res.ok) {
    throw new Error(`Failed to fetch Google Sheet: HTTP ${res.status} ${res.statusText}`)
  }

  const arrayBuffer = await res.arrayBuffer()
  const workbook = XLSX.read(new Uint8Array(arrayBuffer), { type: 'array' })

  console.log(`📋 Available Sheet Tabs: ${workbook.SheetNames.join(', ')}`)

  // Check for Attractions tab or website_input or first sheet with Attractions column
  let targetSheet = workbook.Sheets['Attractions'] || workbook.Sheets['website_input'] || workbook.Sheets['website input']

  if (!targetSheet) {
    for (const sheetName of workbook.SheetNames) {
      const s = workbook.Sheets[sheetName]
      const rows = XLSX.utils.sheet_to_json(s, { header: 1 })
      if (rows.length > 0 && Array.isArray(rows[0]) && rows[0].some(col => String(col).toLowerCase().includes('attraction'))) {
        targetSheet = s
        console.log(`💡 Found attractions in tab: "${sheetName}"`)
        break
      }
    }
  }

  if (!targetSheet) {
    throw new Error('Could not find Attractions or website_input tab in the Google Sheet workbook.')
  }

  const rows = XLSX.utils.sheet_to_json(targetSheet)
  const attractionNames = []
  const seen = new Set()

  for (const row of rows) {
    const rawName = row['Attractions'] || row['Attraction Name'] || row['Attraction'] || row['Name'] || row['name']
    if (rawName && typeof rawName === 'string') {
      const cleanName = rawName.trim()
      if (cleanName && !seen.has(cleanName.toLowerCase())) {
        seen.add(cleanName.toLowerCase())
        attractionNames.push(cleanName)
      }
    }
  }

  if (attractionNames.length === 0) {
    throw new Error('No attraction names found in the sheet!')
  }

  console.log(`✅ Successfully extracted ${attractionNames.length} unique attractions from Google Sheet.`)

  const outputPath = path.resolve(__dirname, '../sanity/schemaTypes/attractionsList.ts')
  const fileContent = `// Auto-generated by scripts/sync-attractions.mjs
// Do not edit manually - run 'npm run sync:attractions' to update

export const ATTRACTION_NAMES = [
${attractionNames.map(name => `  ${JSON.stringify(name)}`).join(',\n')}
]
`

  fs.writeFileSync(outputPath, fileContent, 'utf-8')
  console.log(`💾 Updated: ${outputPath}`)
  console.log('🎉 Attraction Details schema is now 100% in sync with your Google Sheet!')
}

syncAttractions().catch(err => {
  console.error('❌ Sync failed:', err)
  process.exit(1)
})
